#!/usr/bin/env python3
"""dataset.py -- the benchmark data set, independent of any backend.

The data set is split into partitions, one per server host (SERVER_HOSTS).
Partition p holds component ids (p + 1) * 1000 + c for c in
[0, component_ids_per_partition), each with one record per sample.

Every attribute's value is a pure function of its identifying coordinates,
computed generically by core/valuegen.py from the dataset's own JSON
definition -- see design/value-generation.md for the design. There is no
hardcoded per-attribute formula here and no fixed, suite-wide attribute
list: a dataset is defined entirely by its JSON file (dataset/default.json
is one example, modeled on the curated_metrics LDMS sampler plugin's flat
metrics), and defining a new one needs no change to this file or to any
backend writer.

Four attributes are identity/time coordinates, not generated metrics, and
every dataset must declare them by these names:

  timestamp     = t0 + seq * interval
  component_id  = given (the caller's identity for this row; this is what
                  design/value-generation.md calls "node")
  job_id        = 1 + seq // job_len
  seq           = given

Every other flat attribute the definition declares is computed by
valuegen.evaluate() -- see that module and design/value-generation.md
Sec 4. A definition may also declare list attributes (Sec 6): zero or
more attributes with "type": "list", each a per-sample nested list whose
entries are either a flat record of scalar tuple fields or a bare scalar,
with a variable, per-sample length, generated by
valuegen.generate_node_sample(). Dataset exposes this as expected_lists()
(every instance's every attribute, for display/debugging) and, for the
verifier's narrower needs, expected_length() and expected_list_value()
(Sec 6.5's expected_length()/evaluate(attr, C_i), recomputed directly
without generating a list's whole sample). core/bench.py's verifier
implements Sec 6.5's condition grammar (name[i].attr / name[*].attr /
count(name)) against these, used to filter the expected *node* row set a
query should return. What it does not do is validate a list attribute's
own attribute *values* against an already-returned row, since no backend
returns list-attribute values as part of a node row -- see each backend's
README.md for how it maps a list attribute onto its own schema/measurement
instead (Sec 6.5's backend-mapping table; STATUS.md).

Every writer, in any backend, must produce exactly these values; the
query engine verifies answers against them.

After a write, the harness records what was written in a dataset metadata
file, <OUTPUT_DIR>/meta/dataset-<writer>.json. The query engine reads it
so that it verifies against the data actually written, and so that it can
refuse to query a writer whose data was produced by a different backend.

The backend plugin separately records storage-specific information (the
target name it chose, paths, database names, etc.) in an ingest-handoff
meta file at <OUTPUT_DIR>/meta/ingest-handoff-<writer>.json. The query
engine reads that
to discover where the data lives (see core/bench.py's _read_plugin_meta()).

Command line (used by bin/node.sh):
  dataset.py meta WRITER MODE    write the metadata file for WRITER
"""
import datetime
import json
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import valuegen  # noqa: E402

META_FORMAT = 1

# Every dataset definition must declare these four attributes by name;
# their values are the harness's own sampling/partitioning schedule, not
# a hash-generated metric, so they are computed directly rather than
# through valuegen.evaluate(). See the module docstring.
IDENTITY_ATTRS = ("timestamp", "component_id", "job_id", "seq")


class Dataset:
    def __init__(self, definition, partitions, component_ids, samples, t0,
                 interval, job_len):
        attrs_decl = definition.get("attributes", [])
        flat_attrs = [a for a in attrs_decl if a.get("type") != "list"]
        list_attrs = [a for a in attrs_decl if a.get("type") == "list"]
        names = tuple(a["name"] for a in flat_attrs)      # JSON declaration order
        missing = [a for a in IDENTITY_ATTRS if a not in names]
        if missing:
            raise ValueError(f"data set definition is missing required "
                             f"identity attribute(s) {missing}")
        self.definition = definition
        self.attr_names = names
        self._attr_by_name = {a["name"]: a for a in flat_attrs}
        self.list_attrs = list_attrs
        self._list_attr_by_name = {la["name"]: la for la in self.list_attrs}
        self.partitions = partitions
        self.component_ids_per_partition = component_ids
        self.samples = samples
        self.t0 = t0
        self.interval = interval
        self.job_len = job_len
        self._records = None

    # ------------------------------------------------------------ construction

    @staticmethod
    def load_definition(path):
        with open(path) as f:
            return json.load(f)

    @classmethod
    def from_env(cls, live=False):
        """Parameters from the settings exported by bin/node.sh."""
        e = os.environ
        partitions = len(e["SERVER_HOSTS"].split())
        return cls(cls.load_definition(e["DATASET"]), partitions,
                   int(e["COMPONENT_IDS_PER_SERVER"]),
                   int(e["LIVE_SAMPLES"] if live else e["SAMPLES"]),
                   int(e["T0"]), int(e["INTERVAL"]), int(e["JOB_LEN"]))

    @classmethod
    def from_meta(cls, meta):
        p = meta["params"]
        return cls(meta["dataset"], p["partitions"], p["component_ids_per_partition"],
                   p["samples"], p["t0"], p["interval"], p["job_len"])

    def params(self):
        return {"partitions": self.partitions,
                "component_ids_per_partition": self.component_ids_per_partition,
                "samples": self.samples, "t0": self.t0,
                "interval": self.interval, "job_len": self.job_len}

    # ------------------------------------------------------------ contents

    @property
    def name(self):
        return self.definition["name"]

    def attr_type(self, name):
        return self._attr_by_name[name]["type"]

    def size(self):
        return self.partitions * self.component_ids_per_partition * self.samples

    def component_ids(self, partition=None):
        parts = range(self.partitions) if partition is None else [partition]
        return [(p + 1) * 1000 + c for p in parts
                for c in range(self.component_ids_per_partition)]

    @staticmethod
    def partition_of(component_id):
        return component_id // 1000 - 1

    def expected(self, cid, seq):
        """Every flat attribute's value for (cid, seq), keyed by name."""
        timestamp = float(self.t0 + seq * self.interval)
        job_id = 1 + seq // self.job_len
        values = {"timestamp": timestamp, "component_id": cid,
                 "job_id": job_id, "seq": seq}
        for name in self.attr_names:
            if name in IDENTITY_ATTRS:
                continue
            attr = self._attr_by_name[name]
            values[name] = valuegen.evaluate(attr, self.name, cid, "", 0,
                                             job_id, seq)
        return values

    def expected_lists(self, cid, seq):
        """This node's list-attribute entries for (cid, seq) (Sec 6.3).

        Returns a list of dicts, one per entry instance:
          {"list": <name>, "index": <i>, <tuple fields>...}   record entries
          {"list": <name>, "index": <i>, "value": <v>}        bare-scalar entries

        Empty if the definition declares no list attributes. job_id is
        derived the same way expected() derives it, so a caller needing
        both should prefer calling expected() first and deriving job_id
        from its "job_id" key rather than recomputing it, to avoid the
        two ever disagreeing.
        """
        job_id = 1 + seq // self.job_len
        entries = []
        for list_attr in self.list_attrs:
            list_name = list_attr["name"]
            n = valuegen.list_length(self.name, list_attr, cid, job_id, seq)
            entries_spec = list_attr["entries"]
            for i in range(n):
                if entries_spec.get("type") == "record":
                    rec = {"list": list_name, "index": i}
                    for field in entries_spec.get("tuples", []):
                        rec[field["name"]] = valuegen.evaluate(
                            field, self.name, cid, list_name, i, job_id, seq)
                else:
                    rec = {"list": list_name, "index": i,
                           "value": valuegen.evaluate(
                               entries_spec, self.name, cid, list_name, i,
                               job_id, seq, metric_name="")}
                entries.append(rec)
        return entries

    def list_attr(self, name):
        """The list-attribute declaration named *name*, or None."""
        return self._list_attr_by_name.get(name)

    @staticmethod
    def _list_tuple_def(list_attr, attr):
        for a in list_attr["entries"].get("tuples", []):
            if a["name"] == attr:
                return a
        raise KeyError(f"list attribute {list_attr['name']!r} has no tuple field {attr!r}")

    def expected_length(self, name, cid, seq):
        """Expected per-sample length for list attribute *name* (Sec 6.3).

        Recomputes via valuegen.list_length() directly, without
        generating the list's entry values -- the cheap primitive
        core/bench.py's verifier needs for a 'count(name) cmp n'
        condition and for bounds-checking an indexed 'name[i].attr'
        condition.
        """
        la = self.list_attr(name)
        if la is None:
            raise KeyError(f"data set {self.name!r} has no list attribute {name!r}")
        job_id = 1 + seq // self.job_len
        return valuegen.list_length(self.name, la, cid, job_id, seq)

    def expected_list_value(self, name, index, attr, cid, seq):
        """One list entry's value: a tuple field (record entries) or the
        entry itself (bare-scalar entries, attr=None).

        This is Sec 6.5's 'evaluate(attr, C_i)': recomputed directly via
        valuegen.evaluate(), without generating every entry of every
        instance of this list the way expected_lists() does -- the
        narrower, cheaper call the verifier's indexed/existential
        conditions need. Caller is responsible for checking `index` is
        within range (see expected_length()); this does not bounds-check.
        """
        la = self.list_attr(name)
        if la is None:
            raise KeyError(f"data set {self.name!r} has no list attribute {name!r}")
        job_id = 1 + seq // self.job_len
        entries_spec = la["entries"]
        if attr is None:
            return valuegen.evaluate(entries_spec, self.name, cid, name, index,
                                     job_id, seq, metric_name="")
        attr_def = self._list_tuple_def(la, attr)
        return valuegen.evaluate(attr_def, self.name, cid, name, index, job_id, seq)

    def list_tuple_type(self, name, attr=None):
        """The declared type of one list attribute's tuple field, or (when
        attr is None) of a bare-scalar list's own entry type."""
        la = self.list_attr(name)
        if la is None:
            raise KeyError(f"data set {self.name!r} has no list attribute {name!r}")
        if attr is None:
            return la["entries"]["type"]
        return self._list_tuple_def(la, attr)["type"]

    def records(self):
        """Every flat record, as tuples in attr_names order (cached)."""
        if self._records is None:
            self._records = []
            for cid in self.component_ids():
                for seq in range(self.samples):
                    v = self.expected(cid, seq)
                    self._records.append(tuple(v[a] for a in self.attr_names))
        return self._records

    def placeholders(self, limit, literal_formats=None):
        """Values available to query sets as {name}.

        *literal_formats* is an optional dict mapping dataset attribute
        types to format strings (e.g. ``{"timestamp": "to_timestamp({})"}``).
        When provided, placeholder values of that type are wrapped
        accordingly so the generated SQL uses the backend's native literal
        syntax.
        """
        def fmt(val, attr_type):
            if literal_formats and attr_type in literal_formats:
                return literal_formats[attr_type].format(val)
            return val
        def ts(seq):
            return fmt(self.t0 + seq * self.interval, "timestamp")
        s, c, last = self.samples, self.component_ids_per_partition, self.partitions
        mid = s // 2
        return {
            "schema": self.name,
            "limit": limit,
            "t_start": ts(0), "t_end": ts(s - 1),
            "t_q1": ts(s // 4), "t_mid": ts(mid), "t_q3": ts(3 * s // 4),
            "t_mid_1pct": ts(mid + max(1, s // 100)),
            "comp_s0": fmt(1000, "uint64"),
            "comp_s0_last": fmt(1000 + c - 1, "uint64"),
            "comp_slast": fmt(last * 1000, "uint64"),
            "comp_last": fmt(last * 1000 + c - 1, "uint64"),
            "job_first": fmt(1, "uint64"),
            "job_mid": fmt(1 + mid // self.job_len, "uint64"),
            "job_last": fmt(1 + (s - 1) // self.job_len, "uint64"),
        }

# ---------------------------------------------------------------- metadata


def meta_path(writer):
    return os.path.join(os.environ["OUTPUT_DIR"], "meta", f"dataset-{writer}.json")


def write_meta(writer, mode):
    ds = Dataset.from_env(live=(mode == "live"))
    meta = {
        "format": META_FORMAT,
        "backend": os.environ["BACKEND"],
        "writer": writer,
        "write_hosts": os.environ["SERVER_HOSTS"].split(),
        "dataset": ds.definition,
        "params": ds.params(),
        "records": ds.size(),
        "written_at": datetime.datetime.now(datetime.timezone.utc).isoformat(timespec="seconds"),
    }
    path = meta_path(writer)
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w") as f:
        json.dump(meta, f, indent=2)
    print(f"metadata: {path}")


def read_meta(writer):
    path = meta_path(writer)
    if not os.path.exists(path):
        return None
    with open(path) as f:
        meta = json.load(f)
    if meta.get("format") != META_FORMAT:
        raise ValueError(f"{path}: unsupported metadata format {meta.get('format')}")
    return meta


def main(argv):
    if len(argv) == 3 and argv[0] == "meta":
        write_meta(*argv[1:])
        return 0
    print(__doc__, file=sys.stderr)
    return 2


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
